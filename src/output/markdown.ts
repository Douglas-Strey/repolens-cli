/** Markdown report used by `repolens report` and `repolens --markdown`. */
export function renderMarkdown(result: ScanResult, options: MarkdownOptions = {}): string {
  const verbose = options.verbose === true
  const version = text(result.tool.version)
  const name = projectTitle(result) ?? 'Project'
  const description = result.project.description
    ? text(truncate(safeText(result.project.description), DESCRIPTION_LIMIT))
    : null

  const sections: Block[] = [
    overview(result),
    quickStartSection(result),
    architecture(result),
    section('Languages', 2, languagesTable(result)),
    section('Frameworks', 2, frameworksTable(result, verbose)),
    dependencies(result),
    services(result),
    databases(result, verbose),
    environment(result, verbose),
    scripts(result),
    routes(result),
    ci(result),
    tooling(result, verbose),
    git(result),
    issues(result, verbose),
    configFiles(result),
    scanNotes(result, verbose),
  ]
  const hasContent = sections.some((block) => typeof block === 'string')

  // One provenance note, at the top where a reader sees it first.
  return document(
    `# ${name}`,
    description,
    `> Generated by [RepoLens](${REPOLENS_URL}) v${version} — static analysis only, no code was executed. Review before sharing.`,
    ...sections,
    !hasContent && '_RepoLens found nothing to report in this directory._',
  )
}
