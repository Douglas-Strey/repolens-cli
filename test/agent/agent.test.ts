describe('conventions', () => {
  it('derives every rule from the sample data', () => {
    expect(conventions(sampleScanResult())).toEqual([
      'Use pnpm (packageManager field in package.json); do not use npm or yarn.',
      'Use Node.js 22 (`.nvmrc`; other files disagree, see `NODE_VERSION_CONFLICT`) and Go 1.25 (`services/billing/go.mod` go directive).',
      'Run `pnpm lint` and `pnpm test` before finishing a change.',
      'Monorepo (pnpm workspaces, Turborepo): packages live in `apps/*` and `packages/*`; run a package script with `pnpm --filter <package> <script>` (e.g. `pnpm --filter @acme/web dev`).',
      'Never commit `.env` files or paste their values; document new variables in `.env.example`.',
      'CI (GitHub Actions `ci.yml`) runs: lint, typecheck, test, build.',
      'Code style is enforced by Biome (`biome.json`).',
      'Tests use Vitest; end-to-end tests use Playwright.',
      'Database access goes through Prisma (`apps/api/prisma/schema.prisma`).',
    ])
  })

  it('produces no rules without evidence', () => {
    expect(conventions(makeResult())).toEqual([])
  })

  it('names the lockfile when the package manager is not declared', () => {
    const result = makeResult({
      packageManagers: {
        primary: { id: 'npm', name: 'npm', lockfiles: ['package-lock.json'], declared: false, evidence: [] },
        detected: [],
      },
    })
    expect(packageManagerRule(result)).toBe('Use npm (lockfile `package-lock.json`); do not use pnpm or yarn.')
  })

  it('has no package manager rule for non-JavaScript managers', () => {
    const result = makeResult({
      packageManagers: {
        primary: { id: 'go', name: 'Go modules', lockfiles: ['go.sum'], declared: true, evidence: ['go.mod'] },
        detected: [],
      },
    })
    expect(packageManagerRule(result)).toBeNull()
  })

  it('skips runtimes without a version', () => {
    const result = makeResult({ runtimes: [{ id: 'node', name: 'Node.js', version: null, sources: [] }] })
    expect(runtimeRule(result)).toBeNull()
    const ranged = makeResult({
      runtimes: [
        {
          id: 'node',
          name: 'Node.js',
          version: '>=22',
          sources: [{ file: 'package.json', field: 'engines.node', raw: '>=22', version: '>=22', kind: 'range' }],
        },
      ],
    })
    expect(runtimeRule(ranged)).toBe('Use Node.js >=22 (`package.json` engines.node).')
  })

  it('only mentions .env files when the repository has env files', () => {
    expect(envRule(makeResult())).toBeNull()
    const localOnly = makeResult({
      environment: {
        files: [{ path: '.env', kind: 'local', variables: 1, ignored: true, tracked: false }],
        variables: [],
        usageTruncated: false,
      },
    })
    expect(envRule(localOnly)).toBe('Never commit `.env` files or paste their values.')
  })

  it('runs the checks in lint, typecheck, test order', () => {
    const result = sampleScanResult()
    result.scripts.scripts.push({
      name: 'typecheck',
      command: 'tsc --noEmit',
      run: 'pnpm typecheck',
      source: 'package.json',
      package: '.',
      category: 'typecheck',
    })
    expect(verifyRule(result)).toBe('Run `pnpm lint`, `pnpm typecheck` and `pnpm test` before finishing a change.')
  })

  it('describes workspace filtering per package manager', () => {
    expect(filterPattern('pnpm')).toBe('pnpm --filter <package> <script>')
    expect(filterPattern('yarn')).toBe('yarn workspace <package> <script>')
    expect(filterPattern('bun')).toBe('bun run --filter <package> <script>')
    expect(filterPattern('npm')).toBe('npm run <script> -w <directory>')
    expect(filterPattern('go')).toBeNull()
    const result = sampleScanResult()
    if (result.workspace) result.workspace.patterns = ['apps/*', '!apps/legacy']
    expect(workspaceRule(result)).toContain('packages live in `apps/*`;')
  })

  it('limits CI rules and ignores workflows without checks', () => {
    const result = largeScanResult()
    expect(ciRules(result)).toHaveLength(4)
    expect(ciRules(result)[3]).toBe('9 more CI workflows run checks.')
    const deployOnly = sampleScanResult()
    deployOnly.ci.workflows = [
      {
        provider: 'github-actions',
        file: '.github/workflows/deploy.yml',
        triggers: ['push'],
        jobs: [{ id: 'deploy', tasks: ['deploy'], runsOn: [] }],
      },
    ]
    expect(ciRules(deployOnly)).toEqual([])
  })

  it('describes tooling only when it exists', () => {
    const empty = makeResult()
    expect(styleRule(empty)).toBeNull()
    expect(testingRule(empty)).toBeNull()
    expect(ormRule(empty)).toBeNull()
    const e2eOnly = sampleScanResult()
    e2eOnly.testing.tools = e2eOnly.testing.tools.filter((tool) => tool.kind === 'e2e')
    expect(testingRule(e2eOnly)).toBe('End-to-end tests use Playwright.')
  })
})

describe('review regressions', () => {
  it('keeps every file well-formed when committed strings carry Markdown, HTML and escapes', () => {
    const result = { ...hostile(sampleScanResult()), tool: sampleScanResult().tool }
    for (const file of renderAgentFiles(result)) {
      expect(markdownProblems(file.content), file.name).toEqual([])
      expect(file.content.split('\n')[0], file.name).toBe(HEADER)
      expect(withoutCodeSpans(file.content), file.name).not.toMatch(/(?<!\\)<b>/)
      expect(file.content, file.name).not.toMatch(/^#{1,6} H\b/m)
    }
  })

  it("does not forbid other package managers on the strength of RepoLens's npm default", () => {
    const result = makeResult({
      packageManagers: {
        primary: {
          id: 'npm',
          name: 'npm',
          lockfiles: [],
          declared: false,
          evidence: ['package.json without a lockfile'],
        },
        detected: [],
      },
    })
    expect(packageManagerRule(result)).toBeNull()
    const pnpmWorkspace = makeResult({
      packageManagers: {
        primary: {
          id: 'pnpm',
          name: 'pnpm',
          lockfiles: [],
          declared: false,
          evidence: ['workspace file pnpm-workspace.yaml'],
        },
        detected: [],
      },
    })
    expect(packageManagerRule(pnpmWorkspace)).toBe(
      'Use pnpm (workspace file pnpm-workspace.yaml); do not use npm or yarn.',
    )
  })

  it("avoids nested parentheses with the detector's declared-manager evidence", () => {
    const result = makeResult({
      packageManagers: {
        primary: {
          id: 'yarn',
          name: 'Yarn',
          version: '4.10.3',
          lockfiles: ['yarn.lock'],
          declared: true,
          evidence: ['packageManager field in package.json (yarn@4.10.3)', 'lockfile yarn.lock'],
        },
        detected: [],
      },
    })
    expect(packageManagerRule(result)).toBe('Use Yarn (packageManager field in package.json); do not use npm or pnpm.')
  })

  it('says when the files pinning a runtime disagree', () => {
    const result = sampleScanResult()
    expect(runtimeRule(result)).toBe(
      'Use Node.js 22 (`.nvmrc`; other files disagree, see `NODE_VERSION_CONFLICT`) and Go 1.25 (`services/billing/go.mod` go directive).',
    )
    result.doctor.diagnostics = result.doctor.diagnostics.filter((d) => d.code !== 'NODE_VERSION_CONFLICT')
    expect(runtimeRule(result)).toBe('Use Node.js 22 (`.nvmrc`) and Go 1.25 (`services/billing/go.mod` go directive).')
  })

  it('never tells an agent to run the npm placeholder test script or a watcher', () => {
    const result = makeResult({
      packageManagers: {
        primary: { id: 'npm', name: 'npm', lockfiles: ['package-lock.json'], declared: false, evidence: [] },
        detected: [],
      },
      scripts: {
        runner: 'npm run',
        scripts: [
          {
            name: 'test',
            command: 'echo "Error: no test specified" && exit 1',
            run: 'npm test',
            source: 'package.json',
            package: '.',
            category: 'test',
          },
          {
            name: 'lint:watch',
            command: 'esw --watch',
            run: 'npm run lint:watch',
            source: 'package.json',
            package: '.',
            category: 'lint',
          },
        ],
      },
    })
    expect(verifyRule(result)).toBeNull()
    const context = renderAgentContext(result)
    expect(context).not.toContain('npm test')
    expect(context).not.toContain('lint:watch')
    const development = fileMap(result).get('development.md') ?? ''
    expect(development).not.toContain('Before finishing a change')
  })

  it('counts only the kinds of routes that exist in routes.md', () => {
    const result = sampleScanResult()
    result.routes.routes = result.routes.routes.filter((route) => route.kind === 'api')
    expect(fileMap(result).get('routes.md')).toContain('\n6 API routes, found by static analysis.')
    result.routes.routes = sampleScanResult().routes.routes.filter((route) => route.kind === 'page')
    expect(fileMap(result).get('routes.md')).toContain('\n2 pages, found by static analysis.')
  })

  it('keeps agent-context.md short when the description is huge and says how much structure it left out', () => {
    const result = largeScanResult()
    result.project.description = 'word '.repeat(50_000)
    const context = renderAgentContext(result)
    const projectLine = context.split('\n').find((line) => line.startsWith('- word')) ?? ''
    expect(projectLine.length).toBeLessThan(300)
    expect(projectLine).toMatch(/^- (?:word ){30,}word… Monorepo with 60 workspace packages/)
    expect(context).toContain('`dir-8/` (992 files), `dir-9/` (991 files) and 5 more')
    expect(lineCount(context)).toBeLessThan(200)
  })

  it('summarizes CI workflows beyond the limit in development.md', () => {
    const result = largeScanResult()
    const workflow = result.ci.workflows[0]
    if (!workflow) throw new Error('large result has workflows')
    result.ci.workflows = Array.from({ length: 60 }, (_, i) => ({
      ...workflow,
      file: `.github/workflows/w${String(i).padStart(2, '0')}.yml`,
    }))
    expect(fileMap(result).get('development.md')).toContain('_… and 10 more workflows._')
  })

  it('counts doctor findings in plain words, without the info items (UX-22)', () => {
    const intro = (result: ScanResult) =>
      sectionLines(fileMap(result).get('development.md') ?? '', 'Potential issues')[0] ?? ''
    expect(intro(sampleScanResult())).toBe(
      'RepoLens doctor found 1 error and 2 warnings (and 1 info note). Keep them in mind when changing the files involved.',
    )
    const one = sampleScanResult()
    one.doctor.diagnostics = one.doctor.diagnostics.filter((d) => d.code === 'ENV_UNDOCUMENTED')
    expect(intro(one)).toBe('RepoLens doctor found 1 warning. Keep it in mind when changing the files involved.')
  })

  it('never lists platform or test-only variables as undocumented in the agent context (ACC-L2)', () => {
    const result = sampleScanResult()
    const base = result.environment.variables[0]
    if (!base) throw new Error('sample has variables')
    const used = {
      ...base,
      defined: false,
      documented: false,
      used: true,
      documentedIn: [],
      definedIn: [],
      endpoints: [],
    }
    result.environment.variables.push(
      { ...used, name: 'CI' },
      { ...used, name: 'NODE_ENV' },
      { ...used, name: 'npm_lifecycle_event' },
      { ...used, name: 'TEST_ONLY_URL', testOnly: true },
    )
    const lines = sectionLines(renderAgentContext(result), 'Services & environment')
    expect(lines).toContain('- Used in code but undocumented: `STRIPE_SECRET_KEY`')
    expect(renderAgentContext(result)).not.toMatch(/`CI`|NODE_ENV|npm_lifecycle_event|TEST_ONLY_URL/)
  })

  it('never offers a destructive script as the example workspace command (ACC-L2)', () => {
    const result = sampleScanResult()
    result.scripts.scripts.unshift({
      name: 'clean',
      command: 'git clean -xdf',
      run: 'pnpm --filter @acme/api clean',
      source: 'apps/api/package.json',
      package: 'apps/api',
      category: 'other',
    })
    expect(workspaceRule(result)).toContain('(e.g. `pnpm --filter @acme/web dev`)')
    expect(renderAgentContext(result)).not.toContain('clean')
  })

  it('uses the local env file the project keeps (.env.local) in environment.md (UX-12)', () => {
    const result = sampleScanResult()
    result.environment.files = [
      { path: '.env.local', kind: 'local', variables: 3, ignored: true, tracked: false },
      { path: '.env.example', kind: 'example', variables: 4, ignored: false, tracked: true },
    ]
    const environment = fileMap(result).get('environment.md') ?? ''
    expect(environment).toContain(
      'A local `.env.local` exists. Compare it with `.env.example` when variables are added.',
    )
    expect(environment).not.toContain('Fill in the values in `.env`')
    expect(renderAgentContext(result)).not.toContain('cp .env.example')
  })

  it('removes zero-width and tag characters from every agent file (CQ4)', () => {
    const tags = String.fromCodePoint(0xe0049, 0xe0067, 0xe006e, 0xe006f, 0xe0072, 0xe0065)
    const result = sampleScanResult()
    result.project.description = `Acme${String.fromCharCode(0x200b)} storefront${tags}`
    result.environment.variables.push({
      ...(result.environment.variables[0] as ScanResult['environment']['variables'][number]),
      name: `SNEAKY${tags}_KEY`,
    })
    for (const file of renderAgentFiles(result)) {
      expect(file.content, file.name).not.toMatch(/[\u200b]|\udb40[\udc00-\udc7f]/)
    }
  })
})
