const FILE_NAMES = [
  'overview.md',
  'architecture.md',
  'commands.md',
  'environment.md',
  'services.md',
  'routes.md',
  'development.md',
  'agent-context.md',
]

const HEADER = '<!-- Generated by RepoLens v1.2.3. Review before committing. Regenerate with: repolens agent init -->'

function fileMap(result: ScanResult): Map<string, string> {
  return new Map(renderAgentFiles(result).map((file) => [file.name, file.content]))
}

function lineCount(content: string): number {
  return content.trimEnd().split('\n').length
}

/** Lines of one "## Title" section, without the heading and blank lines. */
function sectionLines(content: string, title: string): string[] {
  const lines = content.split('\n')
  const start = lines.indexOf(`## ${title}`)
  if (start === -1) return []
  const rest = lines.slice(start + 1)
  const end = rest.findIndex((line) => line.startsWith('## ') || line === '---')
  return (end === -1 ? rest : rest.slice(0, end)).filter((line) => line !== '')
}

describe('renderAgentFiles', () => {
  it('returns the documented files in a stable order', () => {
    expect(renderAgentFiles(sampleScanResult()).map((file) => file.name)).toEqual(FILE_NAMES)
  })

  it.each(FILE_NAMES)('%s starts with the generated-file header', (name) => {
    const content = fileMap(sampleScanResult()).get(name) ?? ''
    expect(content.startsWith(GENERATED_MARKER)).toBe(true)
    expect(content.split('\n')[0]).toBe(HEADER)
  })

  it.each(FILE_NAMES)('%s matches its snapshot', async (name) => {
    await expect(fileMap(sampleScanResult()).get(name)).toMatchFileSnapshot(`__snapshots__/${name}`)
  })

  it.each([
    ['sample', sampleScanResult],
    ['large result', () => largeScanResult()],
    ['empty result', () => makeResult()],
  ])('every file is well-formed Markdown: %s', (_name, build) => {
    for (const file of renderAgentFiles(build())) {
      expect(markdownProblems(file.content), file.name).toEqual([])
    }
  })

  it('still writes every file, with a title, for an empty result', () => {
    for (const file of renderAgentFiles(makeResult())) {
      expect(file.content.split('\n')[0]).toContain(GENERATED_MARKER)
      expect(file.content).toMatch(/^# .+: project$/m)
      expect(lineCount(file.content)).toBeLessThan(15)
    }
  })

  it('is deterministic', () => {
    expect(renderAgentFiles(sampleScanResult())).toEqual(renderAgentFiles(sampleScanResult()))
  })

  it('caps routes.md and says how many routes were left out', () => {
    const routes = fileMap(largeScanResult()).get('routes.md') ?? ''
    expect(routes).toContain('400 API routes and 100 pages')
    expect(routes).toContain('_… and 300 more routes._')
    expect(routes.split('\n').filter((line) => /^\| (?:GET|POST|PUT|PATCH|DELETE) \|/.test(line))).toHaveLength(200)
  })

  it('documents variable names and where they are documented, never values', () => {
    const environment = fileMap(sampleScanResult()).get('environment.md') ?? ''
    expect(environment).toContain('| `DATABASE_URL` | ✓ | ✓ | ✓ | points at postgres, port 5432 | `.env.example` |')
    expect(environment).toContain('| `STRIPE_SECRET_KEY` | ✗ | ✗ | ✓ | undocumented; not set locally; secret | – |')
    expect(environment).toContain('A local `.env` exists.')
  })

  it('explains how to create .env when only an example exists', () => {
    const result = sampleScanResult()
    result.environment.files = result.environment.files.filter((file) => file.kind === 'example')
    const environment = fileMap(result).get('environment.md') ?? ''
    expect(environment).toContain('1. `cp .env.example .env` — create your local environment file.')
    expect(renderAgentContext(result)).toContain('Create the local env file with `cp .env.example .env`.')
  })

  it('lists setup, checks, CI and doctor findings in development.md', () => {
    const development = fileMap(sampleScanResult()).get('development.md') ?? ''
    expect(sectionLines(development, 'Setup')).toEqual([
      '1. `pnpm db:up` — start local services',
      '2. `pnpm install` — install dependencies',
      '3. `pnpm dev` — start the development server',
    ])
    expect(sectionLines(development, 'Before finishing a change')).toEqual([
      'Run these and make sure they pass:',
      '- `pnpm lint`',
      '- `pnpm test`',
      'If the change affects the build, also run `pnpm build`.',
    ])
    expect(development).toContain('`ci.yml` (GitHub Actions) on push, pull_request: lint, typecheck, test, build')
    expect(development).toContain('- **TRACKED_ENV_FILE** — .env is tracked by Git')
  })

  it('never contains secret values, even when committed text includes them', () => {
    const result = sampleScanResult()
    result.scripts.scripts.push({
      name: 'deploy',
      command: 'API_TOKEN=hunter2 deploy --password s3cret postgres://admin:pw@db/app',
      run: 'API_TOKEN=hunter2 pnpm deploy',
      source: 'package.json',
      package: '.',
      category: 'deploy',
    })
    for (const file of renderAgentFiles(result)) {
      for (const secret of ['hunter2', 's3cret', 'admin:pw']) expect(file.content, file.name).not.toContain(secret)
    }
  })

  it('does not name any particular agent vendor', () => {
    for (const file of renderAgentFiles(sampleScanResult())) {
      expect(file.content).not.toMatch(/claude|codex|cursor|copilot|openai|anthropic/i)
    }
  })

  it.each(['monorepo', 'docker-project', 'broken-env', 'go-api', 'plain-repo', 'bun-app'])(
    '%s fixture: well-formed, no secret values and no absolute paths',
    async (fixture) => {
      const dir = await copyFixture(fixture)
      const result = filterByConfidence(await scanDir(dir))
      for (const file of renderAgentFiles(result)) {
        expect(file.content, file.name).not.toContain(SECRET_SENTINEL)
        expect(file.content, file.name).not.toContain(dir)
        expect(markdownProblems(file.content), file.name).toEqual([])
      }
    },
  )
})

describe('renderAgentContext', () => {
  it('points at companion files only when they are written alongside it', () => {
    const result = sampleScanResult()
    expect(renderAgentContext(result)).toContain('(see `routes.md`)')
    const standalone = renderAgentContext(result, { companionFiles: false })
    expect(standalone).not.toMatch(/see `\w+\.md`/)
    expect(standalone).toContain('(run `repolens agent init` for the full list)')
  })

  it('is the agent-context.md file', () => {
    expect(renderAgentContext(sampleScanResult())).toBe(fileMap(sampleScanResult()).get('agent-context.md'))
  })

  it('has the documented structure', () => {
    const context = renderAgentContext(sampleScanResult())
    const lines = context.split('\n')
    expect(lines[0]).toBe(HEADER)
    expect(lines[2]).toBe('# Agent context: acme-api')
    expect(lines[4]).toBe('_Static analysis only; verify before relying on it._')
    expect(lines.filter((line) => line.startsWith('## '))).toEqual([
      '## Project',
      '## Commands',
      '## Conventions',
      '## Structure',
      '## Services & environment',
      '## API routes',
      '## Potential issues',
    ])
    // The first-line marker names RepoLens; a footer saying it again is gone.
    expect(context.match(/generated by repolens/gi)).toHaveLength(1)
    expect(context).not.toContain('\n---\n')
  })

  it('lists only the commands that exist, with exact run strings', () => {
    expect(sectionLines(renderAgentContext(sampleScanResult()), 'Commands')).toEqual([
      '- Install: `pnpm install`',
      '- Dev: `pnpm dev`',
      '- Test: `pnpm test`',
      '- Lint: `pnpm lint`',
      '- Build: `pnpm build`',
    ])
  })

  it('lists error and warning diagnostics, not infos', () => {
    const issues = sectionLines(renderAgentContext(sampleScanResult()), 'Potential issues')
    expect(issues).toEqual([
      '- `TRACKED_ENV_FILE` (error): .env is tracked by Git. Fix: Run `git rm --cached .env` and add .env to .gitignore.',
      '- `ENV_UNDOCUMENTED` (warning): STRIPE_SECRET_KEY is used in code but missing from .env.example. Fix: Add STRIPE_SECRET_KEY= to .env.example.',
      '- `NODE_VERSION_CONFLICT` (warning): Node.js versions disagree: .nvmrc pins 22, Dockerfile uses 20. Fix: Use the same major version everywhere (22).',
    ])
  })

  it('groups environment variable names', () => {
    const lines = sectionLines(renderAgentContext(sampleScanResult()), 'Services & environment')
    expect(lines).toEqual([
      '- Services (`docker-compose.yml`): `postgres` (5432), `redis` (6379), `minio` (9000, 9001). Start: `pnpm db:up`',
      '- Documented variables (`.env.example`): `API_URL`, `DATABASE_URL`, `LEGACY_FLAG`, `REDIS_URL`',
      '- Used in code but undocumented: `STRIPE_SECRET_KEY`',
    ])
  })

  it('stays under 150 lines for the sample', () => {
    expect(lineCount(renderAgentContext(sampleScanResult()))).toBeLessThan(150)
  })

  it('stays under 200 lines for a large repository (500 routes, 200 variables)', () => {
    const context = renderAgentContext(largeScanResult({ routes: 500, variables: 200 }))
    expect(lineCount(context)).toBeLessThan(200)
    expect(sectionLines(context, 'API routes').filter((line) => line.startsWith('- `'))).toHaveLength(25)
    expect(context).toContain('- … and 375 more API routes (see `routes.md`)')
    expect(context).toContain('- Plus 100 pages (see `routes.md`)')
    expect(context).toContain('more (see `environment.md`)')
    expect(context).toContain('- … and 40 more packages (see `architecture.md`)')
    expect(context).toMatch(/- … and \d+ more \(run `repolens doctor`\)/)
  })

  it('says so when there is nothing to report', () => {
    const context = renderAgentContext(makeResult())
    expect(context).toContain('RepoLens found nothing to report in this directory.')
    expect(context).not.toContain('## ')
  })
})

